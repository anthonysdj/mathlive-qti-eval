// Builds findings/mathml-converters.html from mathml-converters-raw.json: each
// converter's MathML rendered natively by the browser, side by side, and
// screenshots it. This is what a QTI delivery engine without a math renderer
// would show. Usage: pnpm compare && node scripts/gallery.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

const rows = JSON.parse(readFileSync('../../findings/mathml-converters-raw.json', 'utf8'));
const names = Object.keys(rows[0].results);
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const cell = (x) =>
  x.error ? `<td class="bad">error: ${esc(x.error)}</td>`
  : !x.wellFormed ? '<td class="bad">malformed XML (cannot be stored)</td>'
  : `<td${x.empty || x.problems.length || x.missing.length ? ' class="warn"' : ''}>${x.mathml}</td>`;

const temmlCss = readFileSync('node_modules/temml/dist/Temml-Local.css', 'utf8').replace(/@font-face\s*\{[^}]*\}/, '');
const page = (withCss) => `<!doctype html><meta charset="utf-8"><title>MathML converters</title>${withCss ? `<style>${temmlCss}</style>` : ''}
<style>
body{font:14px system-ui,sans-serif;margin:16px;background:#fff;color:#222}
table{border-collapse:collapse} td,th{border:1px solid #ddd;padding:6px 10px;vertical-align:middle}
th{background:#f4f4f4;position:sticky;top:0} td:first-child{font:12px ui-monospace,monospace;max-width:260px}
td math{font-size:22px} .bad{background:#fde8e8;color:#a00;font-size:12px} .warn{background:#fff6dd}
</style>
<h1>Native MathML rendering (Chromium) of each converter's output${withCss ? ', with Temml-Local.css loaded' : ', no extra CSS'}</h1>
<p>Yellow: structural problem or missing content. Red: cannot be stored. Generated by sandbox/converters/scripts/gallery.mjs.</p>
<table><tr><th>LaTeX</th>${names.map((n) => `<th>${n}</th>`).join('')}</tr>
${rows.map((r) => `<tr><td>${esc(r.latex)}</td>${names.map((n) => cell(r.results[n])).join('')}</tr>`).join('\n')}
</table>`;

const browser = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
for (const [suffix, withCss] of [['', false], ['-temml-css', true]]) {
  const file = `../../findings/mathml-converters${suffix}.html`;
  writeFileSync(file, page(withCss));
  const tab = await browser.newPage({ viewport: { width: 1100, height: 800 } });
  await tab.goto('file://' + process.cwd() + '/' + file);
  await tab.screenshot({ path: `../../findings/screenshots/mathml-converters${suffix}.png`, fullPage: true });
  await tab.close();
}
await browser.close();
