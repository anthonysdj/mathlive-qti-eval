// Print path spike: stored MathML (Temml output) → standalone SVG, server-side
// in Node with MathJax, as an image pipeline for an XSL-FO engine such as
// RenderX XEP would need. Writes findings/print-svg-raw.json and a
// side-by-side page comparing the SVG with Chromium's native rendering.
// Usage: pnpm compare && node --experimental-strip-types scripts/print-svg.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
import { mathmlToSvg } from '../src/print-node.ts';

const rows = JSON.parse(readFileSync('../../findings/mathml-converters-raw.json', 'utf8'));
const TEMML = 'Temml 0.14.0';
const out = [];
const t0 = performance.now();
for (const r of rows) {
  const mathml = r.results[TEMML].mathml;
  try {
    const svg = await mathmlToSvg(mathml);
    out.push({
      id: r.id,
      latex: r.latex,
      mathml,
      svg,
      bytes: svg.length,
      paths: (svg.match(/<path /g) ?? []).length,
      error: /data-mjx-error|merror/.test(svg) ? (svg.match(/data-mjx-error="([^"]*)"/)?.[1] ?? 'merror') : undefined,
    });
  } catch (e) {
    out.push({ id: r.id, latex: r.latex, mathml, error: String(e.message ?? e) });
  }
}
const ms = (performance.now() - t0) / rows.length;
writeFileSync('../../findings/print-svg-raw.json', JSON.stringify({ msPerFormula: ms, rows: out }, null, 2));
console.log(`rendered ${out.length} formulas, ${ms.toFixed(1)} ms each`);
for (const o of out) if (o.error || !o.paths) console.log('PROBLEM', o.id, o.error ?? 'no paths');

// Side by side: native MathML (with Temml's CSS, as on screen) vs the SVG image
const temmlCss = readFileSync('node_modules/temml/dist/Temml-Local.css', 'utf8').replace(/@font-face\s*\{[^}]*\}/, '');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const html = `<!doctype html><meta charset="utf-8"><title>Print path: MathML vs SVG</title>
<style>${temmlCss}
body{font:14px system-ui,sans-serif;margin:16px;background:#fff;color:#222}
table{border-collapse:collapse} td,th{border:1px solid #ddd;padding:6px 10px;vertical-align:middle}
th{background:#f4f4f4} td:first-child{font:12px ui-monospace,monospace;max-width:260px}
td math{font-size:22px} td.svg svg{font-size:22px} .bad{background:#fde8e8;color:#a00}
</style>
<h1>Temml MathML: on screen (Chromium, Temml CSS) vs MathJax SVG for print</h1>
<p>Generated by sandbox/converters/scripts/print-svg.mjs.</p>
<table><tr><th>LaTeX</th><th>Screen: native MathML</th><th>Print: SVG image</th><th>SVG size</th></tr>
${out.map((o) => `<tr><td>${esc(o.latex)}</td><td>${o.mathml}</td>${o.svg ? `<td class="svg">${o.svg}</td><td>${(o.bytes / 1024).toFixed(1)} KB</td>` : `<td class="bad" colspan=2>${esc(o.error)}</td>`}</tr>`).join('\n')}
</table>`;
writeFileSync('../../findings/print-svg.html', html);
mkdirSync('../../findings/screenshots', { recursive: true });
const browser = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
await page.goto('file://' + process.cwd() + '/../../findings/print-svg.html');
await page.screenshot({ path: '../../findings/screenshots/print-svg.png', fullPage: true });
await browser.close();
